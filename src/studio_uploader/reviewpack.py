"""Review pack for the reviewer's sign-off (M6) and pilot record (M7).

Collects, into one timestamped folder: preflight results, the latest dry-run
report and its audit events, the channel pin, approval/release/activation
records, ledger, and the test log if supplied.
Writes SUMMARY.md with the PRD's "Done means" checklist pre-filled from that
evidence. Everything is redacted; the credential is never touched.
"""

from __future__ import annotations

import json
import re
import shutil
from datetime import datetime, timezone
from pathlib import Path

from . import __version__, approval
from .config import Config
from .doctor import Check, as_dicts, format_checks
from .redact import redact, redact_text


def _latest_report(cfg: Config, mode: str) -> dict | None:
    best = None
    for p in sorted(cfg.reports_dir.glob("*.json")):
        try:
            r = json.loads(p.read_text())
        except ValueError:
            continue
        if r.get("mode") == mode:
            best = r
    return best


def _events_for(cfg: Config, run_id: str) -> list[dict]:
    out = []
    for p in sorted(cfg.log_dir.glob("audit-*.jsonl")):
        for line in p.read_text().splitlines():
            try:
                e = json.loads(line)
            except ValueError:
                continue
            if e.get("run_id") == run_id:
                out.append(e)
    return out


def build(cfg: Config, checks: list[Check], *, out_dir: Path | None = None,
          test_log: Path | None = None,
          code_version: str = "") -> Path:
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    d = Path(out_dir or cfg.review_packs_dir / stamp)
    d.mkdir(parents=True, exist_ok=False)

    def dump(name: str, obj) -> None:
        (d / name).write_text(json.dumps(redact(obj), indent=2, sort_keys=True) + "\n")

    dump("doctor.json", as_dicts(checks))
    (d / "doctor.txt").write_text(format_checks(checks) + "\n")

    dry = _latest_report(cfg, "dry-run")
    if dry:
        dump("dry-run-report.json", dry)
        dump("dry-run-audit-events.json", _events_for(cfg, dry["run_id"]))
    live = _latest_report(cfg, "live")
    if live:
        dump("live-report.json", live)
        dump("live-audit-events.json", _events_for(cfg, live["run_id"]))

    for src, name in ((cfg.pin_path, "channel_pin.json"), (cfg.activation_path, "activation.json")):
        if src.exists():
            shutil.copyfile(src, d / name)
    recs = d / "approvals"
    recs.mkdir()
    for aid in approval.list_jobs(cfg):
        jd = cfg.frozen_dir / aid
        for f in ("manifest.json", "approval.json"):
            if (jd / f).exists():
                shutil.copyfile(jd / f, recs / f"{aid}.{f}")
        rel = cfg.releases_dir / f"{aid}.json"
        if rel.exists():
            shutil.copyfile(rel, recs / f"{aid}.release.json")
    if cfg.ledger_path.exists():
        (d / "ledger.jsonl").write_text(redact_text(cfg.ledger_path.read_text()))

    tests_ok = None
    if test_log and test_log.exists():
        text = redact_text(test_log.read_text())
        (d / "test-log.txt").write_text(text)
        tests_ok = bool(re.search(r"\b\d+ passed", text)) and not re.search(r"\b\d+ (failed|errors?)\b", text)

    pin_ok = cfg.pin_path.exists()
    dry_ok = bool(dry) and dry.get("upload_requests") == 0 and dry.get("hard_stop") is None
    runbook = Path(__file__).resolve().parents[2] / "docs" / "RUNBOOK.md"

    def box(v):
        return "[x]" if v else "[ ]"

    def note(v, yes, no):
        return yes if v else no

    lines = [
        f"# Review pack {stamp}",
        "",
        f"Uploader version {__version__}{(' / ' + code_version) if code_version else ''}. "
        "Generated by `studio-uploader review-pack`. The reviewer signs off; this file only collects evidence.",
        "",
        "## Done means (PRD)",
        "",
        "- [ ] Code and config reviewed by the reviewer *(reviewer to tick)*",
        f"- {box(dry_ok)} Dry-run evidence: run-once log with every check and zero upload requests "
        f"— {note(dry_ok, 'dry-run-report.json, dry-run-audit-events.json', 'no clean online dry run found (offline runs skip the channel check); run `studio-uploader run`')}",
        f"- {box(pin_ok)} Channel pinned and confirmed by the owner — {note(pin_ok, 'channel_pin.json', 'not pinned')}",
        f"- {box(tests_ok)} All acceptance tests passing — {note(tests_ok, 'test-log.txt', 'supply --test-log from `pytest -q`')}",
        "- [x] Approval record template and manifest schema in place — templates/approval_record.md, schemas/manifest.schema.json",
        f"- {box(runbook.exists())} Disable and revocation runbook written — docs/RUNBOOK.md",
        "",
        "## Preflight",
        "",
        "```",
        format_checks(checks),
        "```",
    ]
    if live:
        lines += ["", "## Latest live run", "",
                  f"- run_id: {live['run_id']}  exit code: {live['exit_code']}  "
                  f"activation: {live.get('activation_id')}"]
        for j in live.get("jobs", []):
            v = j.get("verification") or {}
            lines.append(f"- {j['approval_id']}: {j['outcome']}"
                         + (f", video {j['video_id']}, {v.get('privacyStatus')}, "
                            f"upload {v.get('uploadStatus')}, processing {v.get('processingStatus')}"
                            if j.get("video_id") else f", {j.get('reason', '')}"))
    lines += ["", "Level 3 activation and any publication remain with the reviewer.", ""]
    (d / "SUMMARY.md").write_text("\n".join(lines))
    return d
